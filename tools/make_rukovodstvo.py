def load_spravka(path: Path = HELP_PATH) -> dict:
    """Тексты справки программы — тот же файл, что читает app/ui_help.py."""
    return json.loads(Path(path).read_text(encoding="utf-8"))


def page_intro(key: str, spravka: dict | None = None) -> list[str]:
    """Строки «Как работать с этим шагом» страницы — начало её раздела в руководстве."""
    spravka = spravka if spravka is not None else load_spravka()
    return list(spravka["pages"][key]["steps"])


def page_header(key: str, spravka: dict | None = None) -> str:
    spravka = spravka if spravka is not None else load_spravka()
    return spravka["pages"][key]["header"]


# --- содержание: список блоков (вид, данные) ---------------------------------------
# h1/h2 — заголовки; p — абзац; bullets — список; steps — нумерованный список;
# help — рамка «Как работать…» со строками справки страницы; img — скриншот;
# table — (шапка, строки); note — серая рамка-пояснение; warn — рамка «внимание»;
# pagebreak — новая страница.


def page_blocks(key, title, spravka, image, caption, what, inputs, button, result, extra=()):
    """Раздел одной страницы меню: справка из программы → скриншот → что на странице,
    что вводить, главная кнопка, что получится."""
    blocks = [("h1", title), ("help", key), ("img", image, caption), ("h2", "Что на странице")]
    blocks += [("bullets", what)]
    blocks += [("h2", "Что вводить"), ("bullets", inputs)]
    blocks += [("h2", "Главная кнопка"), ("p", button)]
    blocks += [("h2", "Что получится"), ("p", result)]
    blocks += list(extra)
    return blocks


