def _tokens() -> dict:
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    out = {}
    for token in data["color"]["tokens"]:
        value = token["value"]
        out[token["name"]] = value["light"] if isinstance(value, dict) else value
    return out


def build_docx(out: Path = OUT_DOCX) -> Path:
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Cm, Pt, RGBColor

    tok = _tokens()

    def rgb(name):
        return RGBColor.from_string(tok[name].lstrip("#").upper())

    def hexv(name):
        return tok[name].lstrip("#").upper()

    BODY, HEAD = "Golos Text", "Manrope"
    INK, MUTED, ACCENT = rgb("ink"), rgb("ink-muted"), rgb("accent-ink")
    EMERALD = rgb("emerald-700")
    spravka = load_spravka()

    def font(run, name=BODY, size=None, bold=None, color=None, italic=None):
        run.font.name = name
        rpr = run._element.get_or_add_rPr()
        rfonts = rpr.find(qn("w:rFonts"))
        if rfonts is None:
            rfonts = OxmlElement("w:rFonts")
            rpr.insert(0, rfonts)
        for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            rfonts.set(qn(attr), name)
        if size is not None:
            run.font.size = Pt(size)
        if bold is not None:
            run.font.bold = bold
        if italic is not None:
            run.font.italic = italic
        if color is not None:
            run.font.color.rgb = color

    def para(container, text="", size=10, bold=False, color=INK, name=BODY, after=4, before=0,
             align=None, keep_next=False):
        p = container.add_paragraph()
        pf = p.paragraph_format
        pf.space_after, pf.space_before, pf.line_spacing = Pt(after), Pt(before), 1.1
        pf.keep_with_next = keep_next
        if align is not None:
            p.alignment = align
        if text:
            font(p.add_run(text), name, size, bold, color)
        return p

    def shade(cell, fill):
        tcpr = cell._element.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"), fill)
        tcpr.append(shd)

    def borders(table, color, size=6, edges=("top", "left", "bottom", "right", "insideH", "insideV")):
        tblpr = table._element.tblPr
        el_b = OxmlElement("w:tblBorders")
        for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
            el = OxmlElement(f"w:{edge}")
            if edge in edges:
                el.set(qn("w:val"), "single")
                el.set(qn("w:sz"), str(size))
                el.set(qn("w:color"), color)
            else:
                el.set(qn("w:val"), "nil")
            el.set(qn("w:space"), "0")
            el_b.append(el)
        tblpr.append(el_b)

    def margins(table, top=50, bottom=50, left=90, right=90):
        tblpr = table._element.tblPr
        mar = OxmlElement("w:tblCellMar")
        for k, v in (("top", top), ("left", left), ("bottom", bottom), ("right", right)):
            el = OxmlElement(f"w:{k}")
            el.set(qn("w:w"), str(v))
            el.set(qn("w:type"), "dxa")
            mar.append(el)
        tblpr.append(mar)

    def widths(table, cm):
        tblpr = table._element.tblPr
        layout = OxmlElement("w:tblLayout")
        layout.set(qn("w:type"), "fixed")
        tblpr.append(layout)
        for gc, w in zip(table._element.tblGrid.findall(qn("w:gridCol")), cm):
            gc.set(qn("w:w"), str(int(w * 567)))
        for row in table.rows:
            for c, w in zip(row.cells, cm):
                c.width = Cm(w)

    def row_flags(row, header=False):
        trpr = row._tr.get_or_add_trPr()
        trpr.append(OxmlElement("w:cantSplit"))
        if header:
            trpr.append(OxmlElement("w:tblHeader"))

    def cell_para(cell, first=True):
        p = cell.paragraphs[0] if first else cell.add_paragraph()
        pf = p.paragraph_format
        pf.space_after, pf.space_before, pf.line_spacing = Pt(1), Pt(0), 1.05
        return p

    def box(doc, fill, border, title, lines, numbered=False, title_color=None):
        t = doc.add_table(rows=1, cols=1)
        borders(t, border, 8)
        margins(t, 90, 90, 140, 140)
        c = t.rows[0].cells[0]
        shade(c, fill)
        p = cell_para(c)
        font(p.add_run(title), HEAD, 10.5, True, title_color or ACCENT)
        for n, line in enumerate(lines, 1):
            p = cell_para(c, first=False)
            p.paragraph_format.space_after = Pt(2)
            if numbered:
                font(p.add_run(f"{n}. "), BODY, 9.5, True, ACCENT)
            font(p.add_run(line), BODY, 9.5, color=INK)
        widths(t, (17.6,))
        para(doc, "", after=2)

    def table(doc, head, rows):
        n = len(head)
        total = 17.6
        cm = {2: (5.0, 12.6), 3: (4.6, 7.0, 6.0)}.get(n, tuple(total / n for _ in head))
        t = doc.add_table(rows=1, cols=n)
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        borders(t, hexv("border"))
        margins(t)
        row_flags(t.rows[0], header=True)
        for cell, text in zip(t.rows[0].cells, head):
            shade(cell, hexv("surface-sunken"))
            font(cell_para(cell).add_run(text.upper()), BODY, 7.5, True, MUTED)
        for r in rows:
            row = t.add_row()
            row_flags(row)
            for i, (cell, text) in enumerate(zip(row.cells, r)):
                font(cell_para(cell).add_run(text), BODY, 9, i == 0, INK)
        widths(t, cm)
        para(doc, "", after=2)

    def image(doc, name, caption):
        path = IMG_DIR / name
        if path.exists():
            p = para(doc, after=1, align=WD_ALIGN_PARAGRAPH.CENTER, keep_next=True)
            from PIL import Image  # размер: не выше 12,5 см, не шире поля

            with Image.open(path) as im:
                w, h = im.size
            width = 17.6
            if h / w * width > 12.5:
                width = 12.5 * w / h
            p.add_run().add_picture(str(path), width=Cm(width))
        else:
            para(doc, f"[скриншот «{name}» ещё не снят]", 9, color=MUTED,
                 align=WD_ALIGN_PARAGRAPH.CENTER, after=1)
        para(doc, caption, 8.5, color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER, after=8)

    def field(p, instr, size=8):
        r = p.add_run()
        font(r, BODY, size, color=MUTED)
        for kind, text in (("begin", None), (None, instr), ("end", None)):
            if kind:
                el = OxmlElement("w:fldChar")
                el.set(qn("w:fldCharType"), kind)
            else:
                el = OxmlElement("w:instrText")
                el.set(qn("xml:space"), "preserve")
                el.text = text
            r._element.append(el)

    doc = Document()
    st = doc.styles["Normal"]
    st.font.name, st.font.size = BODY, Pt(10)
    # Запасной Arial для Golos Text / Manrope (их может не быть на компьютере)
    for part in doc.part.package.iter_parts():
        if str(part.partname) == "/word/fontTable.xml":
            xml = part.blob.decode("utf-8")
            add = "".join(
                f'<w:font w:name="{n}"><w:altName w:val="Arial"/><w:charset w:val="CC"/>'
                f'<w:family w:val="swiss"/><w:pitch w:val="variable"/></w:font>'
                for n in (BODY, HEAD) if f'w:name="{n}"' not in xml)
            part._blob = xml.replace("</w:fonts>", add + "</w:fonts>").encode("utf-8")

    sec = doc.sections[0]
    sec.page_height, sec.page_width = Cm(29.7), Cm(21.0)
    sec.orientation = WD_ORIENT.PORTRAIT
    sec.left_margin = sec.right_margin = Cm(1.7)
    sec.top_margin, sec.bottom_margin = Cm(1.8), Cm(1.5)
    sec.header_distance, sec.footer_distance = Cm(0.7), Cm(0.6)
    sec.different_first_page_header_footer = True

    hp = sec.header.paragraphs[0]
    hp.paragraph_format.tab_stops.add_tab_stop(Cm(17.6), alignment=2)
    if LOGO.exists():  # логотипа нет в публичной копии — руководство собирается без него
        hp.add_run().add_picture(str(LOGO), height=Cm(0.55))
    font(hp.add_run("\tРуководство оператора «Бюджет ПИР»"), BODY, 8, color=MUTED)
    fp = sec.footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    font(fp.add_run("стр. "), BODY, 8, color=MUTED)
    field(fp, "PAGE")
    font(fp.add_run(" из "), BODY, 8, color=MUTED)
    field(fp, "NUMPAGES")

    # Обложка: глубокий изумруд дизайн-кода, белый логотип
    cover = doc.add_table(rows=1, cols=1)
    borders(cover, hexv("gradient-to"), 4)
    margins(cover, 420, 420, 500, 500)
    c = cover.rows[0].cells[0]
    shade(c, hexv("emerald-800"))
    p = cell_para(c)
    if LOGO_WHITE.exists():
        p.add_run().add_picture(str(LOGO_WHITE), height=Cm(1.1))
    white = RGBColor(0xFF, 0xFF, 0xFF)
    for text, size, bold, name, before in (
        ("Руководство оператора", 30, True, HEAD, 70),
        ("Программа «Бюджет ПИР» — расчёт бюджета проектно-изыскательских работ", 14, False,
         BODY, 8),
        ("ТЗ → ведомость объёмов → максимальный бюджет (смета) → минимальный бюджет → "
         "сводный бюджет", 10.5, False, BODY, 30),
        (EDITION, 10, False, BODY, 90),
    ):
        p = cell_para(c, first=False)
        p.paragraph_format.space_before = Pt(before)
        font(p.add_run(text), name, size, bold, white)
    widths(cover, (17.6,))

    para(doc, "Содержание", 16, True, EMERALD, HEAD, after=6, before=18)
    blocks = content(spravka)
    for kind, *data in blocks:
        if kind == "h1":
            para(doc, data[0], 10.5, color=INK, after=2)
    para(doc, "Строки справки в начале разделов 4–10 — те же, что программа показывает под "
              "шапкой страницы («Как работать с этим шагом»). Скриншоты сняты на обезличенном "
              "объекте «Т-01».", 9, color=MUTED, before=8)
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    for kind, *data in blocks:
        if kind == "h1":
            para(doc, data[0], 17, True, EMERALD, HEAD, after=6, before=6, keep_next=True)
        elif kind == "h2":
            para(doc, data[0], 12, True, INK, HEAD, after=3, before=8, keep_next=True)
        elif kind == "p":
            para(doc, data[0])
        elif kind in ("bullets", "steps"):
            for n, text in enumerate(data[0], 1):
                p = para(doc, after=2)
                p.paragraph_format.left_indent = Cm(0.6)
                p.paragraph_format.first_line_indent = Cm(-0.45)
                font(p.add_run(f"{n}. " if kind == "steps" else "•  "), BODY, 10, True, ACCENT)
                font(p.add_run(text), BODY, 10, color=INK)
            para(doc, "", after=1)
        elif kind == "help":
            key = data[0]
            label = "Как работать с этим шагом" if key in PAGE_ORDER[:5] else \
                "Как работать с этой страницей"
            box(doc, hexv("accent-soft"), hexv("emerald-100"), f"{label} (справка в программе)",
                page_intro(key, spravka), numbered=True)
        elif kind == "img":
            image(doc, data[0], data[1])
        elif kind == "table":
            table(doc, data[0], data[1])
        elif kind == "note":
            box(doc, hexv("surface-sunken"), hexv("border"), "Обратите внимание", [data[0]],
                title_color=MUTED)
        elif kind == "warn":
            box(doc, hexv("warning-soft"), hexv("warning-soft"), "! Внимание", [data[0]],
                title_color=rgb("warning"))
        elif kind == "pagebreak":
            doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    out.parent.mkdir(parents=True, exist_ok=True)
    doc.save(out)
    return out


def export_pdf(docx: Path = OUT_DOCX, pdf: Path = OUT_PDF) -> Path:
    """PDF через Microsoft Word (как у опросника): поля «стр. N из M» Word обновляет сам."""
    script = (
        "$w = New-Object -ComObject Word.Application; $w.Visible = $false; "
        f"$d = $w.Documents.Open('{docx}'); $d.Fields.Update() | Out-Null; "
        f"$d.ExportAsFixedFormat('{pdf}', 17); $d.Close($false); $w.Quit()"
    )
    subprocess.run(["powershell", "-NoProfile", "-Command", script], check=True)
    return pdf


