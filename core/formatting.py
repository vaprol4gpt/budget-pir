"""Сколько знаков после запятой показывать оператору для колонки
"Кол-во" по единице измерения строки сметы (`EstimateLine.unit`).

Это ТОЛЬКО про отображение (Streamlit-таблица, Excel-выгрузка) — сами
расчёты (`core/models.py`, `core/pricing.py`) не меняются и не знают
про этот модуль. Один общий словарь вместо копий в `app/
streamlit_app.py`/`core/export_excel.py` — оба места должны
показывать одно и то же число знаков для одной и той же единицы.

Единицы, для которых физический смысл однозначен, взяты из реально
встречающихся `unit=` во всех трёх модулях (см.
записи разработки за разбором каждой). Единицы
ВНЕ обоих списков ниже сознательно НЕ угаданы — остаются с прежней
точностью (`DEFAULT_DECIMALS`), см. докстринг `decimals_for_unit`."""

from __future__ import annotations

# Физически считается ШТУКАМИ — 0 знаков после запятой.
INTEGER_UNITS = {
    "программа",  # geology: составление программы работ — 1 штука
    "проба",  # geology: монолиты, пробы воды
    "1 пункт",  # geodesy: опорная геодезическая сеть
    "точек",  # geology: привязка скважин (геодезия внутри геологии)
    "1 точка (выработка)",  # geodesy: привязка геологических выработок
    "ф.т",  # geophysics: физическая точка (ВЭЗ)
    "ф.н.",  # geophysics: физическое наблюдение (МПВ)
    "скв.",  # geology, ведомость: число скважин — поле ввода integer=True
    "отчёт",  # geology, ведомость: технический отчёт — 1 на объект
    "шт",  # ecology: опробование окружающей среды, получение исходных данных —
           # прямой ввод оператора (не дробная формула, как "проба" геологии
           # выше — там значение унаследовано от класса В, здесь всегда целое)
}

# Единицы объёма/протяжённости — дробные, точность НЕ меняется (2
# знака — как и было раньше, до этой правки).
FRACTIONAL_UNITS = {
    "п.м.",  # метраж бурения
    "га",  # площадь топографической съёмки/плана
}

DEFAULT_DECIMALS = 2


def decimals_for_unit(unit: str) -> int:
    """Сколько знаков после запятой показывать для количества с этой
    единицей измерения.

    Единицы вне обоих списков — например, "%" (служебная единица
    строк-процентов kind="B"/"C", где qty всегда 0.0, не настоящее
    количество) и "набл."/"опред."/"анализ"/"компл." (геология:
    название единицы штучное, но САМ ОБЪЁМ в build_volumes считается
    по дробной формуле классов Б/В — например, термометрия = 0.5 ×
    число скважин — то есть в реальной смете может законно получиться
    нецелое число) — сознательно оставлены с DEFAULT_DECIMALS, не
    угаданы. См. записи разработки за полным разбором,
    почему эти конкретные единицы не попали ни в один список."""
    if unit in INTEGER_UNITS:
        return 0
    if unit in FRACTIONAL_UNITS:
        return DEFAULT_DECIMALS
    return DEFAULT_DECIMALS


def format_quantity(value: float, unit: str) -> str:
    """Число "Кол-во" как ТЕКСТ для показа (Streamlit-таблица) — с
    нужным числом знаков по `decimals_for_unit`. Не участвует в
    расчётах, только в отображении. Текст, а не число, потому что
    `st.dataframe`/`column_config` форматирует КОЛОНКУ целиком одним
    правилом — единственный способ показать разную точность для
    разных строк ОДНОЙ колонки "Кол-во" (разные единицы измерения в
    одной таблице сметы) — заранее отформатировать значение в строку
    построчно."""
    decimals = decimals_for_unit(unit)
    return f"{value:.{decimals}f}".replace(".", ",")


def excel_number_format(unit: str) -> str:
    """Excel `number_format` (openpyxl) для колонки "Кол-во" по
    единице измерения — ячейка остаётся ЧИСЛОМ (не текстом, в отличие
    от `format_quantity` для Streamlit), просто с нужным числом
    знаков после запятой, так что сортировка/арифметика в Excel не
    ломается."""
    decimals = decimals_for_unit(unit)
    return "0" if decimals == 0 else "0." + "0" * decimals
