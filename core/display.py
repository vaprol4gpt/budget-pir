"""Как тексты модулей показывать оператору (этап З карты, аудит 05.11.2026, С-4).

Подпись поля модуля бывает абзацем с пунктом таблицы и адресом ячейки эталона, а предупреждений
на смету приходится по 3–7 одного веса — и то, что требует решения, в них теряется. Модули здесь
не меняются: их тексты нужны и в журнале, и в версиях. Меняется только показ.
"""

from __future__ import annotations

import re

# Подпись длиннее — короткая часть в подпись поля, остальное в подсказку «?».
LONG_LABEL = 90
_CUT = re.compile(r" \(| — |\. ")


def split_label(label: str) -> tuple[str, str]:
    """(короткая подпись, подсказка). Короткая подпись не трогается; длинная режется по первой
    скобке, тире или точке. Границу ставим после 15 знаков, чтобы подпись не вышла обрубком."""
    if len(label) <= LONG_LABEL:
        return label, ""
    match = _CUT.search(label, 15)
    if match is None:
        return label, ""
    hint = label[match.start():].strip(" —.")
    if hint.startswith("("):
        hint = hint[1:]
        if hint.endswith(")") and "(" not in hint:
            hint = hint[:-1]
    return label[:match.start()], hint


# Что требует решения оператора и меняет итог; остальное — «к сведению». Список узкий намеренно:
# на смете раздела должно быть видно одно-два действия, а не всё, что программа знает о листе.
_DECISION_MARKS = (
    "Начисления не применены",
    "Отрицательн",
    "Индекс пересчёта цен",
    "Ставка НДС",
    "не применено значение",
    "расчётное значение изменилось",
    "цена не найдена",
    "требуется отдельный источник цены",
    "не найден",
    "не совпадает",
    "Опробование введено",
    "обнуляет строку",
    "не задана — строка = 0",
    "Значение вне",
)


def split_warnings(warnings: list[str]) -> tuple[list[str], list[str]]:
    """(требуют решения, к сведению); порядок внутри каждого списка сохраняется."""
    decisions, notes = [], []
    for text in warnings:
        (decisions if any(mark in text for mark in _DECISION_MARKS) else notes).append(text)
    return decisions, notes
