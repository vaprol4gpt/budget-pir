"""Контракт, которому должен соответствовать каждый модуль программы
(геология, геодезия и т.д.)."""

from dataclasses import dataclass
from typing import Any, Protocol

from core.models import EstimateLine


@dataclass
class Field:
    name: str
    label: str
    type: str
    required: bool
    # Если True — вариантов значений нет в самом Field, их нужно
    # получать через BudgetModule.field_options(name, refs) (см. ниже).
    # По умолчанию False — обычное текстовое/числовое поле, ничего не
    # меняется по сравнению с прежним поведением.
    dynamic_options: bool = False
    # type="group" — повторяющаяся группа строк (оператор добавляет
    # несколько штук на один объект, например "категория грунта +
    # метраж" в геологии или "масштаб + сечение + площадь" в
    # геодезии — см. modules/geology/module.py, modules/geodesy/module.py).
    # group_fields описывает поля ОДНОЙ строки группы (обычные Field,
    # включая dynamic_options); данные оператора для такого поля — это
    # `data[field.name] = list[dict]`, где каждый dict — одна строка,
    # ключи — имена полей из group_fields. Для type != "group" всегда
    # None — не участвует в поведении обычных полей.
    group_fields: list["Field"] | None = None
    # type="number" и physически считается ШТУКАМИ (число скважин,
    # число пунктов и т.п.) — True. Без этого UI (app/streamlit_app.py)
    # рендерит st.number_input с value=float(...) без явного step, а
    # Streamlit сам выбирает step=0.01/format="%0.2f" для float-полей —
    # оператор видит "30,00" вместо "30" уже на этапе ВВОДА, даже если
    # результат сметы (core/formatting.py) уже отформатирован верно.
    # По умолчанию False — прежнее поведение (дробный ввод) для полей,
    # где это уместно (метраж, площадь, сечение).
    integer: bool = False
    # Значение по умолчанию для type="number", когда оператор ещё ничего
    # не вводил. None — прежнее поведение (UI подставляет 0). Нужно для
    # полей-коэффициентов, где 0 — не "пусто", а обнуление строки
    # (например, коэффициент камеральной обработки маршрутных наблюдений
    # экологии, по умолчанию 1 — см. modules/ecology/module.py).
    default: float | None = None
    # Для обязательного type="number": True — 0 считается «не заполнено»
    # (поле имеет смысл только с положительным значением: число скважин,
    # районный коэффициент). False (по умолчанию) — 0 допустимое значение
    # («радон не измеряется»), «не заполнено» — только отсутствие значения
    # (core/validation.py, Э2 дорожной карты 25.10.2026).
    positive: bool = False
    # Наименьшее допустимое значение type="number" (интерфейс не даёт
    # ввести меньше, core/validation.py::below_min_fields проверяет
    # данные, пришедшие не из формы — сохранённые сметы, скрипты).
    # None — без ограничения.
    min_value: float | None = 0


class BudgetModule(Protocol):
    code: str

    def input_schema(self) -> list[Field]:
        """Поля, которые нужно показать оператору для ввода исходных данных."""
        ...

    def field_options(self, field_name: str, refs: Any) -> list[tuple[str, str]]:
        """Варианты значений для поля с `Field.dynamic_options=True` —
        список пар (значение, подпись). Интерфейс вызывает этот метод
        ТОЛЬКО для полей с dynamic_options=True — для остальных полей
        вызывать не нужно (и не гарантируется, что для них метод
        вернёт что-то осмысленное).

        Значение (первый элемент пары) — то, что попадёт в `data` для
        `build_volumes`/`build_estimate`. Подпись (второй элемент) —
        то, что видит оператор в выпадающем списке; может быть
        человекочитаемее значения (например, включать цену).

        Пустой список — легитимный ответ (например, справочник ещё не
        собран или в нём пока нет подходящих позиций), а не повод
        поднимать исключение — вызывающий код должен показать это
        оператору явно, не гадая и не падая."""
        ...

    def build_volumes(self, data: dict, refs: Any) -> dict:
        """Строит ведомость объёмов работ (id вида работ -> объём) по введённым данным."""
        ...

    def build_estimate(self, volumes: dict, refs: Any) -> dict[str, EstimateLine]:
        """Строит смету (строки EstimateLine по id) по ведомости объёмов."""
        ...

    def check(self, estimate: dict[str, EstimateLine]) -> list[str]:
        """Проверяет готовую смету, возвращает список предупреждений оператору."""
        ...


