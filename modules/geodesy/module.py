def match_topo_survey_section(surveys: list[dict], scale: Any) -> Any:
    """Найти сечение рельефа съёмки С ТЕМ ЖЕ масштабом — используется
    UI (app/streamlit_app.py) для предзаполнения новой строки плана
    ПО значению, а не по порядку ввода (см. докстринг модуля выше про
    съёмку/план). Несколько совпадающих съёмок — берётся ПОСЛЕДНЯЯ из
    совпадающих (не последняя вообще). Совпадений нет — None, не
    гадаем (вызывающий код оставляет поле пустым)."""
    matches = [survey for survey in surveys if survey.get("topo_scale") == scale]
    return matches[-1].get("topo_section") if matches else None


def match_topo_survey_area(surveys: list[dict], scale: Any, section: Any) -> Any:
    """То же самое, но для площади — матчит по масштабу И сечению
    ОДНОВРЕМЕННО (не только по масштабу), как и просил заказчик:
    "с тем же масштабом И сечением, что и уже введённая строка
    съёмка"."""
    matches = [
        survey for survey in surveys
        if survey.get("topo_scale") == scale and survey.get("topo_section") == section
    ]
    return matches[-1].get("topo_area") if matches else None


