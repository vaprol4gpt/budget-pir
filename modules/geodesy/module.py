def condition_problem(condition: Any, scale: Any, area: Any) -> str | None:
    """Почему коэффициент условия съёмки к строке НЕ применим (текст для
    оператора) или None — применим. Условия — подписи листа (см.
    STRIP_SCALES / SMALL_* выше)."""
    if condition == CONDITION_STRIP and scale not in STRIP_SCALES:
        return (f"к = 0,7 (полоса вдоль трассы) — только для масштабов 1:500–1:2000, "
                f"а у строки {scale}")
    if condition == CONDITION_SMALL:
        try:
            value = float(area or 0)
        except (TypeError, ValueError):
            value = 0.0
        reasons = []
        if scale != SMALL_SCALE:
            reasons.append(f"масштаб {scale}, а нужен 1:500")
        if not SMALL_AREA_MIN < value <= SMALL_AREA_MAX:
            reasons.append(f"площадь {value:g} га, а нужна свыше 1 до 5 га")
        if reasons:
            return "к = 1,2 (небольшой участок) не подходит: " + "; ".join(reasons)
    if condition == CONDITION_SMALL_2000:
        try:
            value = float(area or 0)
        except (TypeError, ValueError):
            value = 0.0
        reasons = []
        if scale != SMALL_2000_SCALE:
            reasons.append(f"масштаб {scale}, а нужен 1:2000")
        if not 0 < value <= SMALL_2000_AREA_MAX:
            reasons.append(f"площадь {value:g} га, а нужна до 10 га на участок "
                           "(несколько участков — отдельными строками)")
        if reasons:
            return "к = 1,4 (небольшой участок М 1:2000) не подходит: " + "; ".join(reasons)
    return None


