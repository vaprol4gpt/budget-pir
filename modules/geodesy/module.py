def expertise_below_threshold_warning(base: float, created: bool) -> str:
    """Экспертиза включена, а итог сметы не больше 500 тыс. руб. — нижней ступени
    формулы т.80 прим.2 в листах (created — строки экспертизы уже есть: итог
    опустился правками оператора)."""
    total = f"{base:,.0f}".replace(",", " ")
    head = (f"Экспертиза: итог сметы {total} руб. (в ценах 2004 г.) не больше 500 тыс. — формулы "
            "т.80 прим.2 из эталонных листов (свыше 1 млн: ((итог − 1 млн) × 1 % + 18 750) × 1,3; "
            "свыше 500 тыс. до 1 млн: ((итог − 500 тыс.) × 1,5 % + 11 250) × 1,3) к нему "
            "неприменимы. ")
    if created:
        return head + ("Строки экспертизы рассчитаны до правок, после правок итог опустился; "
                       "для итога до 500 тыс. нужен другой пункт т.80 — выключите экспертизу и "
                       "введите её своей строкой (сверить по сборнику СБЦи5.6).")
