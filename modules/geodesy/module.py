def _computer_coef(value: Any) -> float:
    """Коэффициент ОУ п.15: пусто — значение по умолчанию из справочника правил
    параметров (core/param_rules.py, сейчас 1); 0 / меньше 1 — не применяется (1)."""
    if value is None or value == "":
        value = param_rules.default("geodesy", PARAM_COMPUTER, 1.0)
    try:
        coef = float(value)
    except (TypeError, ValueError):
        return 1.0
    return coef if coef > 1.0 else 1.0


