    def stages(self) -> list[Stage]:
        """Ведомость объёмов → смета. Коэффициенты опорной сети (K1,
        K2) и ставка транспорта — константы эталона, не ввод оператора.
        Поля этапа сметы (Э6б) — коэффициент «компьютерные технологии»
        (ОУ п.15) и включение экспертизы (т.80): это параметры расчёта,
        а не объёмы работ."""

        def compute_volumes(inputs, previous, refs, pinned):
            return self.build_volume_sheet(inputs)

        def estimate_before_expertise(inputs, previous, refs):
            # Масштаб и сечение строк съёмки/плана — описание самой
            # позиции ведомости ("что делать"), а не параметр стоимости;
            # в VolumeLine для них нет полей, поэтому они берутся из
            # ввода, зафиксированного в том же неизменяемом снимке
            # ведомости, а площадь — из её строк (см.
            # записи разработки, геодезия).
            sheet = previous["volumes"]
            confirmed_input = sheet.inputs

            def rows(kind, field_name):
                return [
                    {**row, "topo_area": sheet.lines[f"topo_{kind}.{index}"].qty}
                    for index, row in enumerate(confirmed_input.get(field_name) or [])
                ]

            volumes = {
                VK_OPORNY: sheet.lines[VK_OPORNY].qty,
                VK_PRIVYAZKA: sheet.lines[VK_PRIVYAZKA].qty,
                "_topo_surveys": rows("survey", VK_TOPO_SURVEYS),
                "_topo_plans": rows("plan", VK_TOPO_PLANS),
                # позиции Э6б — из строк ведомости (нет строки — 0, как в
                # снимках, подтверждённых до Э6б)
                **{
                    key: (sheet.lines[key].qty if key in sheet.lines else 0)
                    for key in EXTRA_VOLUME_LINES
                },
                **estimate_parameters(inputs),
            }
            # Начисления (С3) — по ставкам данных объекта; не заданы — как раньше.
            # Схема — по параметру «знаки в базе транспорта» (по умолчанию — Автодорога).
            scheme = accruals_scheme(volumes[PARAM_TRANSPORT_MISC])
            return apply_accruals(self.build_estimate(volumes, refs=refs), scheme, refs)

        def expertise_requested(inputs):
            return _expertise_on((inputs or {}).get(PARAM_EXPERTISE))

        def compute_estimate(inputs, previous, refs, pinned):
            estimate = estimate_before_expertise(inputs, previous, refs)
            # Экспертиза — от итога вместе с начислениями (лист G73 от G72);
            # итог до 1 млн — строк нет (add_expertise).
            if expertise_requested(inputs):
                estimate = self.add_expertise(estimate)
            return estimate

        def estimate_context_warnings(inputs, previous, refs):
            warnings = list(accrual_warnings(ACCRUALS, refs))
            if expertise_requested(inputs):
                base = self.expertise_base(estimate_before_expertise(inputs, previous, refs))
                if expertise_bracket(base) is None:
                    warnings.append(expertise_below_threshold_warning(base, created=False))
            return warnings

        def volumes_editable(line, previous):
            # Все строки ведомости геодезии — ввод, меняются в форме.
            return ()

        # Решение №5 + ставка у долей — core/module_helpers.py.
        estimate_editable = estimate_editable_by(volume_key_for_estimate_line)

        return [
            Stage(
                number=1,
                key="volumes",
                title="Ведомость объёмов работ",
                fields=[f for f in self.input_schema() if f.name not in ESTIMATE_PARAMETER_FIELDS],
                compute=compute_volumes,
                editable_fields=volumes_editable,
                confirm_label="Подтвердить ведомость",
                context_warnings=_volume_zero_warnings,
            ),
            Stage(
                number=2,
                key="estimate",
                title="Смета",
                fields=[f for f in self.input_schema() if f.name in ESTIMATE_PARAMETER_FIELDS],
                compute=compute_estimate,
                # Предупреждения модуля — о ценах и об экспертизе, то есть
                # об этапе сметы.
                check=self.check,
                editable_fields=estimate_editable,
                confirm_label="Подтвердить смету",
                context_warnings=estimate_context_warnings,
            ),
        ]

    def check(self, estimate: dict[str, EstimateLine]) -> list[str]:
        warnings = []

        for line in estimate.values():
            if not line.basis.startswith(MISSING_PRICE_BASIS_PREFIX):
                continue
            warnings.append(
                f"Цена для «{line.name}» не найдена в справочнике, "
                "требуется ручная проверка"
            )

        for line in estimate.values():
            marker = f"; {CONDITION_NOT_APPLIED}: "
            if marker in line.basis:
                reason = line.basis.split(marker, 1)[1]
                warnings.append(
                    f"«{line.name}»: выбранное условие съёмки не подходит к строке, коэффициент "
                    f"не применён (к = 1) — {reason}. Проверьте условие или масштаб и площадь."
                )

        oporny = estimate.get("geodesy.oporny_set")
        if oporny is not None and oporny_kameral_missing(
            oporny.qty,
            estimate["geodesy.kameral.oporny_set"].qty if "geodesy.kameral.oporny_set" in estimate else 0,
        ):
            warnings.append(OPORNY_KAMERAL_MISSING_WARNING)

        if EXPERTISE_LINE_ID in estimate:
            cache: dict[str, float] = {}
            base = sum(
                calculate_amount(estimate[i], estimate, cache)
                for i in estimate[EXPERTISE_LINE_ID].base_ids if i in estimate
            )
            bracket = expertise_bracket(base)
            if bracket is None:
                warnings.append(expertise_below_threshold_warning(base, created=True))
            else:
                # сравниваются ступени (по порогу), не ставка: ручная правка ставки
                # строки экспертизы — не смена ступени
                created = created_expertise_bracket(estimate[EXPERTISE_LINE_ID])
                if created is not None and created[0] != bracket[0]:
                    warnings.append(expertise_bracket_changed_warning(base))
            custom_before_index = [
                line.name for line_id, line in estimate.items()
                if is_custom_id(line_id) and line.placement != PLACEMENT_AFTER_INDEX
            ]
            if custom_before_index:
                warnings.append(
                    "Экспертиза считается от строк, рассчитанных программой; свои строки "
                    "(" + ", ".join(f"«{n}»" for n in custom_before_index) + ") в её базу не "
                    "входят, а в листе база экспертизы (G72) — всё «итого по смете». Если своя "
                    "строка — часть работ раздела, добавьте к экспертизе 1,3 % её суммы вручную."
                )

        warnings.append(
            "Состав сметы — позиции эталонного листа «№1.1_ИГДИ» (автодорога) и листа «№2.1_ИГДИ» "
            "(карьер): цены только тех пунктов и категорий, что есть в листах (трасса — III–IV "
            "техническая категория, база — годовой объём до 2 млн руб., съёмка — 1:500, 1:1000 "
            "и 1:2000); внутренний транспорт — 8,75 % («св. 10 до 15 км»), по расстоянию "
            "объекта не выбирается — другую ставку т.4 введите правкой ставки строки. Другие "
            "пункты сборника СБЦи5.6 — вручную."
        )

        return warnings
